-- 1. User Profiles Table (Linked to Supabase auth.users)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'viewer',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    display_name TEXT,
    requested_access BOOLEAN NOT NULL DEFAULT FALSE
);

-- 2. Bins Table (Current Bin State)
CREATE TABLE IF NOT EXISTS public.bins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lat DOUBLE PRECISION NOT NULL,
    long DOUBLE PRECISION NOT NULL,
    fill_level SMALLINT NOT NULL DEFAULT 0,
    time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    battery_level SMALLINT NOT NULL DEFAULT 100,
    location TEXT,
    compost INT,
    recycle INT,
    landfill INT,
    zone TEXT,
    is_deactivated BOOLEAN DEFAULT FALSE
);

-- 3. Telemetry Logs Table (Time-Series Sensor Readings)
CREATE TABLE IF NOT EXISTS public.telemetry_logs (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    bin_id BIGINT NOT NULL REFERENCES public.bins(id) ON DELETE CASCADE,
    fill_level SMALLINT NOT NULL,
    time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    battery_level SMALLINT NOT NULL,
    compost INT,
    recycle INT,
    landfill INT,
    is_manual BOOLEAN
);